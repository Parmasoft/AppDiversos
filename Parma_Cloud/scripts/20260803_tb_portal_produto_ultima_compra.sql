-- Script preparado para Firebird.
-- NAO executado nesta etapa.
-- Objetivo: acrescentar campos de ultima compra no Portal, se ainda nao existirem.

SET SQL DIALECT 3;
SET TERM ^;

EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS(
      SELECT 1
      FROM RDB$RELATION_FIELDS
      WHERE RDB$RELATION_NAME = 'TB_PORTAL_PRODUTO'
        AND RDB$FIELD_NAME = 'PPR_DT_ULTIMA_COMPRA'
  )) THEN
    EXECUTE STATEMENT 'ALTER TABLE TB_PORTAL_PRODUTO ADD PPR_DT_ULTIMA_COMPRA TIMESTAMP';

  IF (NOT EXISTS(
      SELECT 1
      FROM RDB$RELATION_FIELDS
      WHERE RDB$RELATION_NAME = 'TB_PORTAL_PRODUTO'
        AND RDB$FIELD_NAME = 'PPR_NF_ULTIMA_COMPRA'
  )) THEN
    EXECUTE STATEMENT 'ALTER TABLE TB_PORTAL_PRODUTO ADD PPR_NF_ULTIMA_COMPRA VARCHAR(30)';

  IF (NOT EXISTS(
      SELECT 1
      FROM RDB$RELATION_FIELDS
      WHERE RDB$RELATION_NAME = 'TB_PORTAL_PRODUTO'
        AND RDB$FIELD_NAME = 'PPR_SERIE_ULTIMA_COMPRA'
  )) THEN
    EXECUTE STATEMENT 'ALTER TABLE TB_PORTAL_PRODUTO ADD PPR_SERIE_ULTIMA_COMPRA VARCHAR(10)';
END^

SET TERM ;^
COMMIT;
